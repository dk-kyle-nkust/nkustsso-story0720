"""Bilingual navigation and login, including local preferences and editable content."""
from playwright.sync_api import expect


def check_languages(browser, server, screenshots):
    context = browser.new_context(ignore_https_errors=True)
    context.add_init_script("window.cspErrors=[]; document.addEventListener('securitypolicyviolation', e=>window.cspErrors.push(e.violatedDirective));")
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(server + '/portal')
    header = page.locator('.site-header')
    expect(header.get_by_role('link', name='回校首頁', exact=False)).to_have_attribute('href', 'https://www.nkust.edu.tw/index.php')
    expect(header.get_by_role('link', name='忘記密碼', exact=False)).to_have_attribute('href', 'https://resetpassword.nkust.edu.tw/')
    logo = header.locator('img')
    assert logo.evaluate('(img) => img.complete && img.naturalWidth > 0 && Math.abs(img.width / img.height - img.naturalWidth / img.naturalHeight) < .1')
    page.get_by_role('button', name='Switch to English').click()
    expect(page.locator('html')).to_have_attribute('lang', 'en')
    expect(page.get_by_role('heading', name='Faculty & staff', exact=True)).to_be_visible()
    for width in [1440, 1024, 768, 390, 320]:
        page.set_viewport_size({'width': width, 'height': 1000})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        page.screenshot(path=str(screenshots / f'gateway-en-{width}.png'), full_page=True)
        toggle = page.locator('.site-nav-toggle')
        if width <= 760:
            expect(page.locator('#site-navigation')).to_be_hidden()
            toggle.click()
            expect(page.locator('#site-navigation')).to_be_visible()
            page.locator('#site-navigation a').first.focus()
            page.keyboard.press('Escape')
            expect(page.locator('#site-navigation')).to_be_hidden()
            expect(toggle).to_be_focused()
        else:
            expect(toggle).to_be_hidden()
            expect(page.locator('#site-navigation')).to_be_visible()
    page.goto(server + '/faq')
    expect(page.get_by_role('heading', name='FAQ', exact=True)).to_be_visible()
    expect(page.locator('.faq-guide-grid a')).to_have_count(4)
    for summary in page.locator('details > summary').all():
        summary.click()
    expect(page.get_by_text('Do I need to sign in again for another system?', exact=True)).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.screenshot(path=str(screenshots / 'faq-en-320.png'), full_page=True)
    for area in ['student', 'employee', 'alumni']:

        page.goto(server + '/portal/' + area)
        expect(page.locator('html')).to_have_attribute('lang', 'en')
        search = page.get_by_label('Search services', exact=True)
        search.fill('feedback')
        expect(page.locator('#directory-status')).to_have_text('1 service')
        expect(page.locator('.directory-service-name:visible')).to_have_text('Campus feedback')
        page.get_by_role('button', name='切換為繁體中文').click()
        expect(page.locator('#directory-search')).to_have_value('feedback')
        page.get_by_role('button', name='Switch to English').click()
        search.fill('')
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        page.screenshot(path=str(screenshots / f'directory-{area}-en-320.png'), full_page=True)
    page.goto(server + '/portal/student/systems/link-leave')
    expect(page.locator('form.login-form')).to_be_visible()
    original_return = page.locator('[name="ReturnUrl"]').input_value()
    page.get_by_label('Campus account', exact=True).fill('002')
    password = page.locator('#Password')
    password.fill('Wrong!Password123')
    page.get_by_role('button', name='Show password', exact=True).click()
    page.get_by_role('button', name='切換為繁體中文').click()
    expect(page.get_by_role('button', name='隱藏密碼', exact=True)).to_be_visible()
    expect(password).to_have_value('Wrong!Password123')
    assert page.locator('[name="ReturnUrl"]').input_value() == original_return
    page.get_by_role('button', name='Switch to English').click()
    page.get_by_role('button', name='Sign in', exact=True).click()
    expect(page.get_by_role('alert')).to_contain_text('Unable to sign in')
    expect(page.get_by_role('alert')).to_be_focused()
    expect(page.locator('html')).to_have_attribute('lang', 'en')
    for width in [320, 390, 768, 1440]:
        page.set_viewport_size({'width': width, 'height': 1000})
        for detail in page.locator('details').all():
            if detail.get_attribute('open') is None:
                detail.locator('summary').click()
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
        page.screenshot(path=str(screenshots / f'login-en-{width}.png'), full_page=True)
    page.get_by_label('Password', exact=True).fill('123456')
    page.locator('[name="ReturnUrl"]').evaluate("el=>el.value='/'")
    page.get_by_role('button', name='Sign in', exact=True).click()
    page.wait_for_url(server + '/')
    expect(page.get_by_role('heading', name='Students', exact=True)).to_be_visible()
    expect(page.locator('#portal-pinned, #portal-recent, #portal-search')).to_have_count(0)
    page.goto(server + '/portal/student')
    expect(page.get_by_label('Search services', exact=True)).to_be_visible()
    second = context.new_page()
    second.goto(server + '/portal')
    expect(second.locator('html')).to_have_attribute('lang', 'en')
    page.get_by_role('button', name='切換為繁體中文').click()
    expect(second.locator('html')).to_have_attribute('lang', 'zh-Hant')
    assert not errors, errors
    assert page.evaluate('window.cspErrors.length') == 0
    context.close()
    # 禁止儲存、停用腳本都不能阻擋原本的中文入口。
    blocked = browser.new_context(ignore_https_errors=True)
    blocked.add_init_script("Object.defineProperty(window, 'localStorage', {get(){throw new Error('blocked')}})")
    fallback = blocked.new_page()
    fallback.goto(server + '/portal')
    fallback.get_by_role('button', name='Switch to English').click()
    expect(fallback.locator('html')).to_have_attribute('lang', 'en')
    blocked.close()
    nojs = browser.new_context(ignore_https_errors=True, java_script_enabled=False, viewport={'width': 320, 'height': 900})
    fallback = nojs.new_page()
    fallback.goto(server + '/portal')
    expect(fallback.locator('#site-navigation')).to_be_visible()
    expect(fallback.locator('[data-language-switch]')).to_be_hidden()
    nojs.close()
    print('PASS bilingual navigation, English search/login/errors, responsive layout, persisted language, unchanged form data, unified home, blocked storage and no-JS fallback')
